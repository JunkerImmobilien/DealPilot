-- „setz das bitte vollumfänglich um“).
--
--   reseller_clients      Zugangsart (Partnerplatz / eigener Plan), Stufe, Rechte, Kontingent, Marke, Netzwerk,
--                         Verbindung (bestätigt, getrennt), Platzentzug mit Frist, Plan vor dem Platz (Plan-Schutz)
--   partner_anfragen      Verbindungsanfrage an ein BESTEHENDES Konto (Einladung oder Code) - erst die Bestätigung
--                         des Kunden legt die Verbindung an
--   verbindungs_codes     Einmal-Code, den der Kunde erzeugt (nur SHA-256, 24 h), Vorbild telegram_links (076)
--   object_shares         Senden als KOPIE: Kopie-Objekt, Stand, Bestand
--   objects               kunden_freigabe_id: die Kopie eines Kundenstands (NULL = eigenes Objekt des Nutzers)
--   partner_aufgaben(+_kunden)  Aufgaben an Kunden mit Status je Kunde
--   partner_meldungen     Glocke beim Partner
--
-- Idempotent.

ALTER TABLE public.reseller_clients
    ADD COLUMN IF NOT EXISTS platz_art        text NOT NULL DEFAULT 'platz',      -- 'platz' (Partner zahlt) | 'eigen' (Kunde zahlt)
    ADD COLUMN IF NOT EXISTS stufe            smallint,                            -- 1 Einsteiger, 2 Fortgeschritten, 3 Experte (nur platz)
    ADD COLUMN IF NOT EXISTS rechte           jsonb,                               -- NULL = alles wie Investor
    ADD COLUMN IF NOT EXISTS kontingent       jsonb,                               -- z. B. {"marktbericht": 3}
    ADD COLUMN IF NOT EXISTS marke            text NOT NULL DEFAULT 'partner',     -- 'partner' | 'dealpilot'
    ADD COLUMN IF NOT EXISTS netzwerk         boolean NOT NULL DEFAULT false,      -- Partnernetzwerk sichtbar
    ADD COLUMN IF NOT EXISTS herkunft         text,                                -- einladung | code | uebergabe | alt
    ADD COLUMN IF NOT EXISTS verbunden_am     timestamptz,
    ADD COLUMN IF NOT EXISTS getrennt_am      timestamptz,
    ADD COLUMN IF NOT EXISTS getrennt_von     text,                                -- partner | kunde | entzug | abo_ende
    ADD COLUMN IF NOT EXISTS entzug_am        timestamptz,
    ADD COLUMN IF NOT EXISTS entzug_frist_bis timestamptz,
    ADD COLUMN IF NOT EXISTS entzug_erledigt_am timestamptz,
    ADD COLUMN IF NOT EXISTS plan_vorher      text,                                -- Plan-Schutz: Plan, den der Platz ersetzt hat
    ADD COLUMN IF NOT EXISTS berater_id       uuid REFERENCES public.users(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS notiz            text;                                -- intern, nie beim Kunden
-- Bestand: wer schon Kunde war, gilt als verbunden seit Anlage
UPDATE public.reseller_clients SET verbunden_am = created_at, herkunft = COALESCE(herkunft, 'alt')
 WHERE verbunden_am IS NULL;

ALTER TABLE public.reseller_invites
    ADD COLUMN IF NOT EXISTS art            text NOT NULL DEFAULT 'neu',         -- 'neu' | 'verbindung'
    ADD COLUMN IF NOT EXISTS platz_mitgeben boolean NOT NULL DEFAULT true;

CREATE TABLE IF NOT EXISTS public.partner_anfragen (
    id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    reseller_id    uuid NOT NULL REFERENCES public.resellers(id) ON DELETE CASCADE,
    user_id        uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    quelle         text NOT NULL,                       -- einladung | code
    platz_mitgeben boolean NOT NULL DEFAULT false,
    anzeige_name   text,
    status         text NOT NULL DEFAULT 'offen',       -- offen | angenommen | abgelehnt | zurueckgezogen
    erstellt_von   uuid REFERENCES public.users(id) ON DELETE SET NULL,
    erstellt_am    timestamptz NOT NULL DEFAULT now(),
    beantwortet_am timestamptz
);
CREATE INDEX IF NOT EXISTS idx_partner_anfragen_user ON public.partner_anfragen (user_id, status);
CREATE UNIQUE INDEX IF NOT EXISTS uq_partner_anfragen_offen ON public.partner_anfragen (reseller_id, user_id) WHERE status = 'offen';

CREATE TABLE IF NOT EXISTS public.verbindungs_codes (
    id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id        uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    code_hash      text NOT NULL UNIQUE,
    gueltig_bis    timestamptz NOT NULL,
    eingeloest_von uuid REFERENCES public.resellers(id) ON DELETE SET NULL,
    eingeloest_am  timestamptz,
    widerrufen_am  timestamptz,
    erstellt_am    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_verbindungs_codes_user ON public.verbindungs_codes (user_id);

-- Fehlversuche beim Einlösen (5 je Partner und Stunde)
CREATE TABLE IF NOT EXISTS public.verbindungs_code_versuche (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reseller_id uuid NOT NULL REFERENCES public.resellers(id) ON DELETE CASCADE,
    erstellt_am timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_vc_versuche ON public.verbindungs_code_versuche (reseller_id, erstellt_am);

ALTER TABLE public.object_shares
    ADD COLUMN IF NOT EXISTS kopie_object_id uuid REFERENCES public.objects(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS stand_am        timestamptz,
    ADD COLUMN IF NOT EXISTS stand_nr        integer NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS ueber_bestand   boolean NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS aufgabe_id      uuid,
    ADD COLUMN IF NOT EXISTS gelesen_am      timestamptz;

ALTER TABLE public.objects
    ADD COLUMN IF NOT EXISTS kunden_freigabe_id uuid REFERENCES public.object_shares(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_objects_kunden_freigabe ON public.objects (kunden_freigabe_id) WHERE kunden_freigabe_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.partner_aufgaben (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    reseller_id     uuid NOT NULL REFERENCES public.resellers(id) ON DELETE CASCADE,
    titel           text NOT NULL,
    text            text,
    art             text NOT NULL DEFAULT 'frei',      -- steuerjahr | bestand_senden | frei
    steuerjahr      integer,
    objektfilter    text NOT NULL DEFAULT 'alle',      -- alle | bestand | ankauf
    faellig_am      date,
    erinnerung_tage integer NOT NULL DEFAULT 7,
    erstellt_von    uuid REFERENCES public.users(id) ON DELETE SET NULL,
    erstellt_am     timestamptz NOT NULL DEFAULT now(),
    status          text NOT NULL DEFAULT 'aktiv'      -- aktiv | abgeschlossen
);
CREATE INDEX IF NOT EXISTS idx_partner_aufgaben_reseller ON public.partner_aufgaben (reseller_id, status);

CREATE TABLE IF NOT EXISTS public.partner_aufgaben_kunden (
    aufgabe_id            uuid NOT NULL REFERENCES public.partner_aufgaben(id) ON DELETE CASCADE,
    client_id             uuid NOT NULL REFERENCES public.reseller_clients(id) ON DELETE CASCADE,
    status                text NOT NULL DEFAULT 'offen',   -- offen | gesehen | in_arbeit | erledigt | abgelehnt
    gesehen_am            timestamptz,
    erledigt_am           timestamptz,
    abgelehnt_grund       text,
    letzte_erinnerung_am  timestamptz,
    PRIMARY KEY (aufgabe_id, client_id)
);
CREATE INDEX IF NOT EXISTS idx_pak_client ON public.partner_aufgaben_kunden (client_id, status);

CREATE TABLE IF NOT EXISTS public.partner_meldungen (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    reseller_id uuid NOT NULL REFERENCES public.resellers(id) ON DELETE CASCADE,
    client_id   uuid REFERENCES public.reseller_clients(id) ON DELETE CASCADE,
    art         text NOT NULL,
    text        text,
    share_id    uuid REFERENCES public.object_shares(id) ON DELETE SET NULL,
    aufgabe_id  uuid REFERENCES public.partner_aufgaben(id) ON DELETE SET NULL,
    gelesen_am  timestamptz,
    erstellt_am timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_partner_meldungen ON public.partner_meldungen (reseller_id, gelesen_am, erstellt_am DESC);
